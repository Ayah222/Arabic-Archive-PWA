export default function FAQPage() {
  const [open, setOpen] = useState<number | null>(null);
  const [q, setQ] = useState("");

  const filtered = q.trim()
    ? FAQS.filter((f) => f.q.includes(q) || f.a.includes(q))
    : FAQS;

  return (
    <div className="p-4 md:p-8 max-w-3xl mx-auto space-y-6" dir="rtl">
      <div>
        <h1 className="text-2xl font-bold text-foreground">الأسئلة الشائعة</h1>
        <p className="text-sm text-muted-foreground mt-1">إجابات على أكثر الأسئلة شيوعاً</p>
      </div>

      <input
        value={q}
        onChange={(e) => setQ(e.target.value)}
        placeholder="ابحث في الأسئلة..."
        className="w-full px-4 py-2.5 rounded-xl border border-border bg-card focus:outline-none focus:ring-2 focus:ring-primary text-sm"
        dir="rtl"
      />

      {filtered.length === 0 ? (
        <p className="text-muted-foreground text-sm">لا توجد نتائج لـ «{q}»</p>
      ) : (
        <div className="space-y-3">
          {filtered.map((faq, i) => {
            const idx = FAQS.indexOf(faq);
            const isOpen = open === idx;
            return (
              <div
                key={idx}
                className="liquid-glass-card rounded-2xl overflow-hidden transition-all duration-200"
              >
                <button
                  className="w-full flex items-center gap-3 px-5 py-4 text-right"
                  onClick={() => setOpen(isOpen ? null : idx)}
                >
                  <span className="text-2xl shrink-0">{faq.icon}</span>
                  <span className="flex-1 font-semibold text-sm text-foreground">{faq.q}</span>
                  <span className="text-muted-foreground text-lg shrink-0 transition-transform duration-200" style={{ transform: isOpen ? "rotate(45deg)" : "none" }}>+</span>
                </button>
                {isOpen && (
                  <div className="px-5 pb-4 text-sm text-muted-foreground leading-relaxed whitespace-pre-line border-t border-border/40 pt-3">
                    {faq.a}
                  </div>
                )}
              </div>
            );
          })}
        </div>
      )}
    </div>
  );
}
